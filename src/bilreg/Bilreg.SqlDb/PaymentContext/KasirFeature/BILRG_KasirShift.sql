CREATE TABLE BILRG_KasirShift (
    ShiftId VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_ShiftId DEFAULT(''),
    TglShift VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_TglShift DEFAULT('3000-01-01'),
    KodeShift VARCHAR(5) NOT NULL CONSTRAINT DF_BILRG_KasirShift_KodeShift DEFAULT(''),
    KasirId VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_KasirId DEFAULT(''),
    Loket VARCHAR(20) NOT NULL CONSTRAINT DF_BILRG_KasirShift_Loket DEFAULT(''),
    TglJamBuka VARCHAR(19) NOT NULL CONSTRAINT DF_BILRG_KasirShift_TglJamBuka DEFAULT('3000-01-01 00:00:00'),
    SaldoAwal DECIMAL(18,2) NOT NULL CONSTRAINT DF_BILRG_KasirShift_SaldoAwal DEFAULT(0),
    TglJamTutup VARCHAR(19) NOT NULL CONSTRAINT DF_BILRG_KasirShift_TglJamTutup DEFAULT('3000-01-01 00:00:00'),
    SaldoAkhirFisik DECIMAL(18,2) NOT NULL CONSTRAINT DF_BILRG_KasirShift_SaldoAkhirFisik DEFAULT(0),
    TotalTerimaSistem DECIMAL(18,2) NOT NULL CONSTRAINT DF_BILRG_KasirShift_TotalTerimaSistem DEFAULT(0),
    TotalKeluarSistem DECIMAL(18,2) NOT NULL CONSTRAINT DF_BILRG_KasirShift_TotalKeluarSistem DEFAULT(0),
    StatusShift VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_StatusShift DEFAULT('BUKA'),
    crttgl VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_crttgl DEFAULT('3000-01-01'),
    crtjam VARCHAR(8) NOT NULL CONSTRAINT DF_BILRG_KasirShift_crtjam DEFAULT('00:00:00'),
    crtusr VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_KasirShift_crtusr DEFAULT(''),
    updtgl VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_KasirShift_updtgl DEFAULT('3000-01-01'),
    updjam VARCHAR(8) NOT NULL CONSTRAINT DF_BILRG_KasirShift_updjam DEFAULT('00:00:00'),
    updusr VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_KasirShift_updusr DEFAULT(''),

    CONSTRAINT PK_BILRG_KasirShift PRIMARY KEY CLUSTERED (ShiftId)
);
GO

CREATE NONCLUSTERED INDEX IX_BILRG_KasirShift_KasirId_Status
    ON BILRG_KasirShift (KasirId, StatusShift);
GO

CREATE NONCLUSTERED INDEX IX_BILRG_KasirShift_TglShift
    ON BILRG_KasirShift (TglShift);
GO
