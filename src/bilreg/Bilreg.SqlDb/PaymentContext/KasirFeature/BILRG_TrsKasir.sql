    TotalNilai DECIMAL(18,2) NOT NULL CONSTRAINT DF_BILRG_TrsKasir_TotalNilai DEFAULT(0),
    StatusTrs VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_TrsKasir_StatusTrs DEFAULT('BERHASIL'),
    TglVoid VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_TrsKasir_TglVoid DEFAULT('3000-01-01'),
