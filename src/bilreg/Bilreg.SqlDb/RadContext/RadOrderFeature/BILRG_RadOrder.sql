CREATE TABLE BILRG_RadOrder (
    OrderId VARCHAR(13) NOT NULL CONSTRAINT DF_BILRG_RadOrder_OrderId DEFAULT(''),
    EmrOrderId VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadOrder_EmrOrderId DEFAULT(''),
    OrderNo VARCHAR(20) NOT NULL CONSTRAINT DF_BILRG_RadOrder_OrderNo DEFAULT(''),
    OrderSource INT NOT NULL CONSTRAINT DF_BILRG_RadOrder_OrderSource DEFAULT(0),
    Modality VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_RadOrder_Modality DEFAULT(''),
    RadOrderStatus INT NOT NULL CONSTRAINT DF_BILRG_RadOrder_RadOrderStatus DEFAULT(1),
    Urgency INT NOT NULL CONSTRAINT DF_BILRG_RadOrder_Urgency DEFAULT(0),

    RegId VARCHAR(15) NOT NULL CONSTRAINT DF_BILRG_RadOrder_RegId DEFAULT(''),
    PatientId VARCHAR(20) NOT NULL CONSTRAINT DF_BILRG_RadOrder_PatientId DEFAULT(''),
    PatientName VARCHAR(60) NOT NULL CONSTRAINT DF_BILRG_RadOrder_PatientName DEFAULT(''),
    BirthDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadOrder_BirthDate DEFAULT('3000-01-01'),
    Gender VARCHAR(1) NOT NULL CONSTRAINT DF_BILRG_RadOrder_Gender DEFAULT(''),
    AgeAtOrder INT NOT NULL CONSTRAINT DF_BILRG_RadOrder_AgeAtOrder DEFAULT(0),

    DokterPengorderId VARCHAR(12) NOT NULL CONSTRAINT DF_BILRG_RadOrder_DokterPengorderId DEFAULT(''),
    DokterPengorderName VARCHAR(100) NOT NULL CONSTRAINT DF_BILRG_RadOrder_DokterPengorderName DEFAULT(''),
    LayananPengorderId VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_RadOrder_LayananPengorderId DEFAULT(''),
    LayananPengorderName VARCHAR(100) NOT NULL CONSTRAINT DF_BILRG_RadOrder_LayananPengorderName DEFAULT(''),
    ClinicalNote VARCHAR(500) NOT NULL CONSTRAINT DF_BILRG_RadOrder_ClinicalNote DEFAULT(''),

    CancelledReason VARCHAR(200) NOT NULL CONSTRAINT DF_BILRG_RadOrder_CancelledReason DEFAULT(''),
    CancelledDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadOrder_CancelledDate DEFAULT('3000-01-01'),
    CancelledUserId VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadOrder_CancelledUserId DEFAULT(''),

    CrtUser VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadOrder_CrtUser DEFAULT(''),
    CrtDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadOrder_CrtDate DEFAULT('3000-01-01'),
    UpdUser VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadOrder_UpdUser DEFAULT(''),
    UpdDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadOrder_UpdDate DEFAULT('3000-01-01'),
    VodUser VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadOrder_VodUser DEFAULT(''),
    VodDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadOrder_VodDate DEFAULT('3000-01-01'),

    CONSTRAINT PK_BILRG_RadOrder PRIMARY KEY CLUSTERED (OrderId)
);
GO

CREATE INDEX IX_BILRG_RadOrder_Status ON BILRG_RadOrder(RadOrderStatus, CrtDate);
GO
CREATE INDEX IX_BILRG_RadOrder_Reg ON BILRG_RadOrder(RegId, RadOrderStatus) WHERE RegId <> '';
GO
CREATE INDEX IX_BILRG_RadOrder_OrderNo ON BILRG_RadOrder(OrderNo);
GO
CREATE INDEX IX_BILRG_RadOrder_EmrOrderId ON BILRG_RadOrder(EmrOrderId) WHERE EmrOrderId <> '';
GO
CREATE INDEX IX_BILRG_RadOrder_Modality ON BILRG_RadOrder(Modality, RadOrderStatus, CrtDate);
GO
CREATE INDEX IX_BILRG_RadOrder_PatientRecent ON BILRG_RadOrder(PatientId, Modality, CrtDate);
GO
