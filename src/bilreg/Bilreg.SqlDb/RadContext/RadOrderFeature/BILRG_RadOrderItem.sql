CREATE TABLE BILRG_RadOrderItem (
    OrderId VARCHAR(13) NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_OrderId DEFAULT(''),
    ItemNo INT NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_ItemNo DEFAULT(0),
    TarifId VARCHAR(12) NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_TarifId DEFAULT(''),
    TarifName VARCHAR(100) NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_TarifName DEFAULT(''),
    Modality VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_Modality DEFAULT(''),
    Urgency INT NOT NULL CONSTRAINT DF_BILRG_RadOrderItem_Urgency DEFAULT(0),

    CONSTRAINT PK_BILRG_RadOrderItem PRIMARY KEY CLUSTERED (OrderId, ItemNo)
);
GO

CREATE INDEX IX_BILRG_RadOrderItem_Tarif ON BILRG_RadOrderItem(TarifId, OrderId);
GO
