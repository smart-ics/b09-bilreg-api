CREATE TABLE BILRG_RadTarifModality (
    TarifId VARCHAR(12) NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_TarifId DEFAULT(''),
    TarifName VARCHAR(100) NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_TarifName DEFAULT(''),
    Modality VARCHAR(10) NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_Modality DEFAULT(''),
    IsActive BIT NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_IsActive DEFAULT(1),

    CrtUser VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_CrtUser DEFAULT(''),
    CrtDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_CrtDate DEFAULT('3000-01-01'),
    UpdUser VARCHAR(50) NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_UpdUser DEFAULT(''),
    UpdDate DATETIME NOT NULL CONSTRAINT DF_BILRG_RadTarifModality_UpdDate DEFAULT('3000-01-01'),

    CONSTRAINT PK_BILRG_RadTarifModality PRIMARY KEY CLUSTERED (TarifId)
);
GO

CREATE INDEX IX_BILRG_RadTarifModality_Modality ON BILRG_RadTarifModality(Modality, IsActive);
GO
