/// <summary>
/// Data transfer object rincian satu baris item tagihan penjualan farmasi (tb_trs_dobill_umum2).
/// </summary>
public record PenjualanItemResponse(
    int NoUrut,
    string PenjualanItemId,
    string BrgId,
    string BrgName,
    string SatuanId,
    string SatuanName,
    decimal Qty,
    decimal HargaSatuan,
    decimal Diskon,
    decimal Biaya,
    decimal TaxProsen,
    decimal TaxRupiah,
    decimal Fee,
    decimal Total,
    string Etiket,
    decimal EtiketQty,
    decimal EtiketHari,
    string EtiketKdPakai,
    string EtiketCatatan,
    bool IsRacik,
    bool IsKomponen,
    string RacikId,
    bool IsBeliBebas,
    decimal NilaiKlaim,
    bool IsVoid)
{
    public static PenjualanItemResponse FromModel(PenjualanItemModel model) => new(
        model.NoUrut,
        model.PenjualanItemId,
        model.BrgId,
        model.BrgName,
        model.SatuanId,
        model.SatuanName,
        model.Qty,
        model.HargaSatuan,
        model.Diskon,
        model.Biaya,
        model.TaxProsen,
        model.TaxRupiah,
        model.Fee,
        model.Total,
        model.Etiket,
        model.EtiketQty,
        model.EtiketHari,
        model.EtiketKdPakai,
        model.EtiketCatatan,
        model.IsRacik,
        model.IsKomponen,
        model.RacikId,
        model.IsBeliBebas,
        model.NilaiKlaim,
        model.IsVoid);
}

